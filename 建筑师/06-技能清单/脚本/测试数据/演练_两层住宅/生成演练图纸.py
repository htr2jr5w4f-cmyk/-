# PDF：PyMuPDF 直接按同一套几何画，1:100 @ A3 横向；每个 CAD 图层对应一个 PDF 图层（OCG）
# ---------------------------------------------------------------------------
def 生成pdf(路径):
    import pymupdf
    pt = 72.0 / 25.4
    W, H = 420 * pt, 297 * pt
    doc = pymupdf.open()
    ocg = {名: doc.add_ocg(名, on=True) for 名, _ in 图层表}
    字体文件 = "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc"
    字 = dict(fontname="wqy", fontfile=字体文件) if os.path.exists(字体文件) else dict(fontname="china-s")
    样式 = {"外墙": ((0, 0, 0), 0.7), "内墙": ((0, 0, 1), 0.35), "门窗块": ((1, 0, 0), 0.25), "湿区": ((0, 0.6, 0.6), 0.25),
          "尺寸": ((0.5, 0.5, 0.5), 0.18), "楼梯": ((0, 0.5, 0), 0.25), "屋面": ((0.8, 0, 0.8), 0.35), "图框": ((0, 0, 0), 0.5)}

    for 图, _文件, 带表 in 图纸:
        page = doc.new_page(width=W, height=H)
        Q = lambda x, y: pymupdf.Point((x + 平面偏移[0]) / 100 * pt, H - (y + 平面偏移[1]) / 100 * pt)  # 平面坐标 mm → pt
        S = lambda x, y: pymupdf.Point(x / 100 * pt, H - y / 100 * pt)                                # 图框坐标 mm → pt

        def 线(a, b, 层, dashes=None):
            c, w = 样式[层]
            page.draw_line(a, b, color=c, width=w, oc=ocg[层], dashes=dashes)

        def 环(pts, 层, fill=None, 描边=True, dashes=None):
            c, w = 样式[层]
            page.draw_polyline(pts + [pts[0]], color=c if 描边 else None, fill=fill, width=w, closePath=True,
                               oc=ocg[层], dashes=dashes)

        def 文(p, t, 层="文字", size=7):
            page.insert_text(p, t, fontsize=size, oc=ocg[层], **字)

        # 图框和图签
        环([S(0, 0), S(42000, 0), S(42000, 29700), S(0, 29700)], "图框")
        环([S(27000, 0), S(42000, 0), S(42000, 6000), S(27000, 6000)], "图框")
        for i, t in enumerate([标注, 标注英, "布里斯班两层住宅（演练）Class 1a，约 260 m²",
                               f"{图['编号']}  {图['图名']}", "比例 SCALE 1:100 @ A3   版次 REV A（演练）  2026-11-21"]):
            文(S(27300, 5200 - i * 1000), t, size=9 if i == 0 else 7)
        # 外墙、内墙
        for r in 图.get("外墙", []):
            环([Q(*p) for p in r], "外墙")
        for a, b in 图.get("内墙", []):
            线(Q(*a), Q(*b), "内墙")
        # 湿区：浅色填充（无描边）+ 淋浴区描边
        for r in 图.get("湿区填充", []):
            环([Q(*p) for p in r], "湿区", fill=(0.85, 0.95, 1.0), 描边=False)
        for r in 图.get("湿区线", []):
            环([Q(*p) for p in r], "湿区")
        # 门窗：按块画（窗三线、门扇 + 开启弧折线、推拉门两线、车库门两线）
        宽 = {k: w for k, w, _h, _d in 门窗表}
        for 块, x, y, rot, 编号 in 图.get("门窗", []):
            ca, sa = math.cos(math.radians(rot)), math.sin(math.radians(rot))
            R = lambda u, v: Q(x + u * ca - v * sa, y + u * sa + v * ca)
            if 块.startswith("W"):
                for v in (-60, 0, 60):
                    线(R(0, v), R(宽[编号], v), "门窗块")
            elif 块 in ("DOOR820", "ENTRY1020"):
                w = 宽[编号]
                线(R(0, 0), R(0, w), "门窗块")
                pts = [R(w * math.cos(math.radians(a)), w * math.sin(math.radians(a))) for a in range(0, 91, 10)]
                for i in range(len(pts) - 1):
                    线(pts[i], pts[i + 1], "门窗块")
